const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),C=require(path.join(root,'Аналитика разработки бота/mindmap-core.js'));
const registry=JSON.parse(fs.readFileSync(path.join(root,'docs/mindmap_v9/logic_registry_v9.json'),'utf8'));
const all=C.graph(registry,{expanded:registry.branches.map(b=>b.letter)});
assert.equal(all.visibleRules,registry.rule_count);assert.equal(all.nodes.length,registry.rule_count+16);assert.equal(all.edges.length,registry.rule_count+15);
assert.equal(new Set(all.nodes.map(x=>x.id)).size,registry.rule_count+16);
for(const b of registry.branches)for(const rule of b.items)assert(all.nodes.some(n=>n.id===rule.id));
assert.equal(C.graph(registry).visibleRules,0);
assert.equal(C.graph(registry,{query:'A01'}).visibleRules,1);
assert.equal(C.graph(registry,{query:'xyz-not-a-rule'}).visibleRules,0);
const filtered=C.graph(registry,{status:'LIVE'});
assert(filtered.nodes.filter(n=>n.type==='rule').every(n=>n.status.split('/')[0]==='LIVE'));
const moved=C.graph(registry,{expanded:['A'],positions:{A01:{x:100,y:200},A02:{x:Infinity,y:0}}});
assert.equal(moved.nodes.find(n=>n.id==='A01').x,100);
assert(Number.isFinite(moved.nodes.find(n=>n.id==='A02').x));
const initial={scale:.5,x:100,y:20},anchor={x:350,y:200},zoom=C.zoom(initial,1.2,anchor);
assert(Math.abs((anchor.x-zoom.x)/zoom.scale-(anchor.x-initial.x)/initial.scale)<1e-8);
const fitted=C.fit(all.bounds,1200,680);assert(fitted.scale>0&&fitted.scale<=1.2);
for(const e of all.edges)assert(C.edgePath(all.nodes.find(n=>n.id===e.from),all.nodes.find(n=>n.id===e.to)).startsWith('M '));
assert.deepEqual(C.histogram([0,9,10,100,null,undefined,NaN],[0,10,100]).map(b=>b.count),[2,2]);
console.log('Mind map:',registry.rule_count,'rules, unique nodes, filtering, saved drag positions, zoom anchor, fit and histogram boundaries passed');
