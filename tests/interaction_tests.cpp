#include "psyz0r/behavior.hpp"
#include <iostream>
using namespace psyz0r;
int main() {
    int failures=0;
    auto check=[&](bool ok,const char* label){if(!ok){std::cerr<<label<<'\n';++failures;}};
    Behavior b;
    auto event=[&](unsigned id,double time,EventKind kind,int amount=0,const char* corpse="",Weapon weapon=Weapon::None,const char* opponent="human") {
        Event e{id,time,kind,amount}; e.opponent_id=opponent;e.source="synthetic_test";
        e.verified=true;e.corpse_id=corpse;e.weapon=weapon;b.observe(e);
    };
    Observation o; o.opponent_id="human";o.time=1;o.enemy_visible=true;
    o.enemy_distance=48;o.safe_close_contact=true;o.enemy_hp_estimate_valid=true;o.enemy_hp_estimate=40;
    o.available_weapons={Weapon::Rocket,Weapon::Gauntlet};
    check(!b.decide(o).revenge_gauntlet,"weapon selection alone has no reaction");
    Event unverified{1,1,EventKind::GauntletDamage,100}; b.observe(unverified);
    check(!b.reaction("human"),"unverified damage rejected");
    event(2,2,EventKind::GauntletDamage,25);o.time=2;
    check(!b.decide(o).revenge_gauntlet,"below threshold");
    event(2,2,EventKind::GauntletDamage,25);
    check(b.reaction("human")->gauntlet_damage==25,"duplicate damage ignored");
    event(3,12,EventKind::GauntletDamage,25);o.time=12;
    check(b.decide(o).weapon==Weapon::Gauntlet,"damage accumulates across encounters and attempts finish");
    o.enemy_distance=400;
    check(b.decide(o).weapon!=Weapon::Gauntlet,"no reckless cross-map gauntlet");
    o.enemy_distance=48;o.enemy_visible=false;
    check(b.decide(o).weapon!=Weapon::Gauntlet,"no hidden target gauntlet");
    o.enemy_visible=true;o.safe_close_contact=false;
    check(b.decide(o).weapon!=Weapon::Gauntlet,"unsafe approach rejected");
    o.safe_close_contact=true;o.enemy_hp_estimate_valid=false;
    check(b.decide(o).weapon!=Weapon::Gauntlet,"no ungrounded enemy HP");
    o.enemy_hp_estimate_valid=true;o.enemy_hp_estimate=80;
    check(b.decide(o).weapon!=Weapon::Gauntlet,"healthy target rejected");
    o.enemy_hp_estimate=40;o.health=20;
    check(b.decide(o).intent==Intent::Recover&&b.decide(o).weapon!=Weapon::Gauntlet,"own survival priority");
    o.health=100;event(4,13,EventKind::BotKilledOpponent,0,"enemy1",Weapon::Rocket);o.time=13;
    check(b.decide(o).revenge_gauntlet,"rocket kill does not fulfill gauntlet revenge");
    event(5,14,EventKind::BotKilledOpponent,0,"other",Weapon::Gauntlet,"other");o.time=14;
    check(b.decide(o).revenge_gauntlet,"wrong opponent kill does not complete revenge");
    event(6,15,EventKind::BotKilledOpponent,0,"enemy2",Weapon::Gauntlet);o.time=15;
    check(!b.decide(o).revenge_gauntlet,"confirmed target gauntlet kill completes revenge");
    event(7,16,EventKind::OpponentCorpseShot,0,"own1");
    event(8,16,EventKind::OpponentCorpseShot,0,"own1");
    event(9,17,EventKind::OpponentCorpseShot,0,"own2");
    check(b.reaction("human")->corpse_episodes==2&&!b.reaction("human")->corpse_retaliation,"two episodes ignored, burst deduped");
    event(10,18,EventKind::OpponentCorpseShot,0,"own3");
    check(b.reaction("human")->corpse_retaliation,"third corpse enables retaliation");
    o.time=18;o.enemy_visible=false;o.corpse_visible=true;o.safe_corpse_action=true;
    o.corpse_owner_id="human";o.corpse_id="unknown";
    check(!b.decide(o).attack_visible_corpse,"must be own confirmed kill corpse");
    event(11,18,EventKind::BotKilledOpponent,0,"enemy3",Weapon::Rocket);
    o.corpse_id="enemy3";
    check(b.decide(o).attack_visible_corpse,"safe visible killed opponent corpse response");
    o.time=19;
    check(!b.decide(o).attack_visible_corpse,"one second action cap");
    o.corpse_visible=false;b.decide(o);o.corpse_visible=true;
    check(!b.decide(o).attack_visible_corpse,"same corpse cannot restart series");
    o.time=120;
    check(b.reaction("human")->corpse_retaliation,"retaliation remains until end of match");
    b.forget_opponent("human");check(!b.reaction("human"),"disconnect/team switch clears opponent");
    b.reset_match();check(!b.reaction("other"),"match reset clears all opponents");
    BehaviorSettings s;s.gauntlet_damage=25;
    Behavior tuned(Style::Thoughtful,s);
    Event hit{1,1,EventKind::GauntletDamage,25};hit.verified=true;hit.source="synthetic_test";hit.opponent_id="human";
    tuned.observe(hit);o={};o.opponent_id="human";o.time=1;
    check(tuned.decide(o).revenge_gauntlet,"configurable 25 damage threshold");
    o.time=91;check(!tuned.decide(o).revenge_gauntlet,"90 second expiry");
    return failures?1:0;
}
