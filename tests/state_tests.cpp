#include "psyz0r/behavior.hpp"
#include "psyz0r/item_memory.hpp"
#include <iostream>
using namespace psyz0r;
int main() {
    int failed=0;
    auto check=[&](bool ok,const char* name){if(!ok){std::cerr<<name<<'\n';++failed;}};
    BehaviorSettings s; s.surrender_probability=1; s.lead_tilt_probability=0;
    Observation o; o.time=30; o.opponent_score=5; o.available_weapons={Weapon::Machinegun,Weapon::Rail};
    auto deaths=[](Behavior& bot){for(int i=1;i<=3;++i)bot.observe({static_cast<unsigned>(i),static_cast<double>(i),EventKind::OpponentKilledBot});};
    Behavior surrender(Style::Thoughtful,s); deaths(surrender);
    auto d=surrender.decide(o);
    check(d.mood==Mood::SurrenderTilt&&!d.collect_resources&&d.items==ItemPriority::None,"automatic forfeit");
    check(d.weapon==Weapon::Machinegun,"first available weapon");
    o.alive=false; o.time=31;
    check(surrender.decide(o).intent==Intent::Hold,"forfeit waits while dead");
    o.alive=true;o.health=100;o.bot_score=2;o.time=32;
    check(surrender.decide(o).mood==Mood::SurrenderTilt,"accidental frags cannot cancel forfeit");
    surrender.reset_match();o.opponent_score=0;o.bot_score=0;o.time=0;
    check(surrender.decide(o).mood==Mood::Normal,"new match resets surrender");
    s.surrender_duration=10;
    Behavior temporary(Style::Thoughtful,s);deaths(temporary);o.time=30;o.opponent_score=5;
    check(temporary.decide(o).mood==Mood::SurrenderTilt,"finite forfeit starts");
    o.time=40;check(temporary.decide(o).mood==Mood::Normal,"finite forfeit expires without retrigger");
    s.surrender_probability=0;s.surrender_duration=0;
    Behavior never(Style::Thoughtful,s);deaths(never);o.time=30;
    check(never.decide(o).mood==Mood::Normal,"probability zero");
    o.time=100;check(never.decide(o).mood==Mood::Normal,"no per-frame reroll");
    s.surrender_probability=1;s.surrender_enabled=false;
    Behavior disabled(Style::Thoughtful,s);deaths(disabled);o.time=30;
    check(disabled.decide(o).mood==Mood::Normal,"disabled surrender");
    s.surrender_enabled=true;
    Behavior deficit(Style::Thoughtful,s);deaths(deficit);o.bot_score=3;
    check(deficit.decide(o).mood==Mood::Normal,"score gap and own score gates");
    o.bot_score=0;o.opponent_score=0;
    Behavior relaxed(Style::Thoughtful,s);o.bot_score=20;
    check(relaxed.decide(o).mood==Mood::Relaxed,"big lead relaxation");
    o.opponent_score=7;o.time=31;check(relaxed.decide(o).mood==Mood::Normal,"relaxation ends after configured concessions");
    s.lead_tilt_probability=1;
    Behavior throwing(Style::Thoughtful,s);o.opponent_score=0;o.time=30;
    check(throwing.decide(o).mood==Mood::LeadLossTilt,"separate lead loss tilt");
    o.bot_score=0;o.opponent_score=20;o.time=31;
    check(throwing.decide(o).mood==Mood::LeadLossTilt,"lead loss tilt survives score reversal");
    Behavior adapting; o={};o.time=21;
    adapting.observe({1,1,EventKind::OpponentPush});
    check(adapting.decide(o).style==Style::Thoughtful,"one event does not switch style");
    for(unsigned i=2;i<=9;++i)adapting.observe({i,21,EventKind::OpponentPush});
    check(adapting.decide(o).style==Style::Aggressive,"accumulated aggressive observations");
    for(unsigned i=10;i<=30;++i)adapting.observe({i,22,EventKind::OpponentRetreat});
    o.time=22;check(adapting.decide(o).style==Style::Aggressive,"minimum style hold");
    o.time=42;check(adapting.decide(o).style==Style::Passive,"hysteresis switches after hold");
    ItemMemory items;
    check(!items.pickup("mega",1,35,false)&&!items.estimate("mega"),"hidden pickup rejected");
    check(items.pickup("mega",1,35,true)&&items.estimate("mega")->expected_respawn==36,"observed pickup timer");
    check(!items.pickup("mega",1,35,true),"duplicate item event rejected");
    items.reset();check(!items.estimate("mega"),"map resets item memory");
    Behavior combat;
    combat.observe({1,20,EventKind::OwnDamageReceived,45});
    combat.observe({2,21,EventKind::OwnDamageReceived,40});
    o={};o.time=21;
    check(combat.decide(o).intent==Intent::Recover,"damage accumulated in engagement");
    o.time=27;check(combat.decide(o).intent==Intent::Hold,"damage episode expires");
    combat.set_style(Style::Passive);combat.observe({3,28,EventKind::OwnRailHit});o.time=28;
    check(combat.decide(o).intent==Intent::Recover,"rail event retreat");
    Behavior collector; o={};o.time=1;
    o.item_candidates={{"red",ItemKind::Red,0,1},{"mega",ItemKind::Mega,0,3},{"yellow",ItemKind::Yellow,0,1}};
    check(collector.decide(o).target_item=="mega","opening mega goal");
    o.health=20;o.time=2;
    check(collector.decide(o).target_item=="yellow","recovery yellow goal");
    Behavior relax_resources(Style::Thoughtful,s);s.lead_tilt_probability=0;
    Behavior weak_relax(Style::Thoughtful,s);o={};o.time=30;o.bot_score=20;
    check(!weak_relax.decide(o).collect_resources,"relaxed bot leaves resources");
    o.health=20;o.time=31;
    check(weak_relax.decide(o).collect_resources,"relaxed bot still recovers low health");
    Behavior low_confidence(Style::Aggressive);o={};o.time=30;o.enemy_visible=true;
    o.damage_dealt=90;o.favorable_fight_estimate=true;o.estimate_confidence=0.2;
    check(low_confidence.decide(o).intent!=Intent::Push,"uncertain damage does not authorize push");
    return failed?1:0;
}
